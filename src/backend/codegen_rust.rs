#[derive(Default, Debug)]
pub struct ArenaSector {
    allocated_count: usize,
    items: Vec<Box<dyn std::any::Any>>,
}

impl ArenaSector {
    pub fn new() -> Self { Self::default() }
    pub fn insert<T: 'static>(&mut self, val: T) {
        self.items.push(Box::new(val));
        self.allocated_count += 1;
    }
    pub fn reset(&mut self) {
        self.items.clear();
    }
    pub fn count(&self) -> i64 {
        self.items.len() as i64
    }
    pub fn allocated(&self) -> i64 {
        self.allocated_count as i64
    }
}

pub struct MemArena;
impl MemArena {
    pub fn allocate(&self) -> ArenaSector { ArenaSector::new() }
}

pub struct MemModule { pub arena: MemArena }
pub static mem: MemModule = MemModule { arena: MemArena };
pub static Mem: MemModule = MemModule { arena: MemArena };

pub struct TimeModule;
impl TimeModule {
    #[inline(always)]
    pub fn now_ms(&self) -> i64 {
        std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_millis() as i64
    }
    #[inline(always)]
    pub fn elapsed(&self, start: i64) -> i64 {
        self.now_ms() - start
    }
    #[inline(always)]
    pub fn benchmark<F: FnOnce()>(&self, f: F) -> i64 {
        let t0 = Instant::now();
        f();
        t0.elapsed().as_millis() as i64
    }
}
pub static time: TimeModule = TimeModule;
pub static Time: TimeModule = TimeModule;

#[inline(always)]
pub fn alpha_index<T: Clone>(v: &Vec<T>, idx: i64) -> T {
    v[(idx - 1) as usize].clone()
}

#[inline(always)]
pub fn alpha_index_mut<'a, T>(v: &'a mut Vec<T>, idx: i64) -> &'a mut T {
    &mut v[(idx - 1) as usize]
}

#[inline(always)]
pub fn alpha_map_get<K: std::hash::Hash + Eq, V: Clone>(m: &HashMap<K, V>, key: &K) -> V {
    m.get(key).cloned().expect("Key not found in map")
}

